// Headless determinism check: runs every simulation exactly as the benchmark
// does (same frame counts, same chunking) without a GPU and prints the
// verification hashes. Results must be identical on every CPU architecture,
// compiler and thread count. Used to generate core/reference_hashes.h.
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "../../core/bench_spec.h"
#include "../../core/platform.h"
#include "../../core/sim_asteroids.h"
#include "../../core/sim_city.h"
#include "../../core/sim_particles.h"
#include "../../core/sim_physics.h"

using namespace tsb;

static double now_s() { return ns_to_s(plat::time_ns()); }

int main(int argc, char** argv) {
    u32 threads = 3;
    bool header = false;
    for (int i = 1; i < argc; ++i) {
        if (!strcmp(argv[i], "--threads") && i + 1 < argc) threads = (u32)atoi(argv[++i]);
        if (!strcmp(argv[i], "--header")) header = true;
    }
    JobSystem jobs;
    jobs.start(threads);
    JobChain chain;
    u64 h[4][MODE_COUNT];
    const u32 nStd = kGtFrames[MODE_STANDARD], nQuick = kGtFrames[MODE_QUICK];

    {
        AsteroidSim sim;
        sim.init(kAsteroidCount);
        void* dst = mem_alloc(sim.instance_bytes());
        AsteroidFrame fr;
        double t0 = now_s();
        u64 visSum = 0;
        for (u32 f = 1; f <= nStd; ++f) {
            sim.build(chain, f, dst, &fr);
            jobs.dispatch(&chain);
            jobs.wait(&chain);
            visSum += fr.visible;
            if (f == nQuick) h[0][MODE_QUICK] = sim.hash();
        }
        h[0][MODE_STANDARD] = sim.hash();
        fprintf(stderr, "gt1 asteroids: %.2f ms/frame, avg visible %.0f\n", (now_s() - t0) * 1000.0 / nStd,
                (double)visSum / nStd);
        mem_free(dst);
        sim.release();
    }
    {
        ParticleSim sim;
        sim.init(kParticleCount);
        void* dst = mem_alloc(sim.instance_bytes());
        ParticleFrame fr;
        double t0 = now_s();
        for (u32 f = 1; f <= nStd; ++f) {
            sim.build(chain, f, dst, &fr);
            jobs.dispatch(&chain);
            jobs.wait(&chain);
            if (f == nQuick) h[1][MODE_QUICK] = sim.hash();
        }
        h[1][MODE_STANDARD] = sim.hash();
        fprintf(stderr, "gt2 particles: %.2f ms/frame\n", (now_s() - t0) * 1000.0 / nStd);
        mem_free(dst);
        sim.release();
    }
    {
        CitySim sim;
        sim.init();
        void* dst[CitySim::DST_COUNT];
        for (int i = 0; i < CitySim::DST_COUNT; ++i) dst[i] = mem_alloc(sim.dst_bytes(i));
        CityFrame fr;
        double t0 = now_s();
        u64 visSum = 0;
        for (u32 f = 1; f <= nStd; ++f) {
            sim.build(chain, f, dst, &fr);
            jobs.dispatch(&chain);
            jobs.wait(&chain);
            visSum += fr.visibleBuildings;
            if (f == nQuick) h[2][MODE_QUICK] = sim.hash();
        }
        h[2][MODE_STANDARD] = sim.hash();
        fprintf(stderr, "gt3 city: %.3f ms/frame, avg visible buildings %.0f\n", (now_s() - t0) * 1000.0 / nStd,
                (double)visSum / nStd);
        for (int i = 0; i < CitySim::DST_COUNT; ++i) mem_free(dst[i]);
        sim.release();
    }
    {
        PhysicsSim sim;
        sim.init(kPhysicsCount);
        for (int mode = 0; mode < MODE_COUNT; ++mode) {
            u32 st = kPhysStepsST[mode], mt = kPhysStepsMT[mode];
            sim.reset();
            double t0 = now_s();
            for (u32 s = 0; s < st; ++s) {
                sim.build(chain);
                jobs.run_inline(&chain);
                sim.advance();
            }
            double tST = now_s() - t0;
            u64 hST = sim.hash();
            sim.reset();
            u64 hAtST = 0;
            t0 = now_s();
            for (u32 s = 0; s < mt; ++s) {
                sim.build(chain);
                jobs.dispatch(&chain);
                jobs.wait(&chain);
                sim.advance();
                if (s + 1 == st) hAtST = sim.hash();
            }
            double tMT = now_s() - t0;
            h[3][mode] = sim.hash();
            fprintf(stderr, "cpu physics [%s]: ST %.2f ms/step, MT(%u workers+1) %.2f ms/step, ST==MT: %s\n",
                    mode == MODE_STANDARD ? "standard" : "quick", tST * 1000.0 / st, threads, tMT * 1000.0 / mt,
                    hST == hAtST ? "yes" : "NO");
            if (hST != hAtST) return 2;
        }
        sim.release();
    }
    jobs.stop();

    const char* ids[4] = {"gt1", "gt2", "gt3", "cpu"};
    if (header) {
        printf("// Generated by hosts/simcheck (simcheck --header). Do not edit by hand.\n");
        printf("#pragma once\n\n#include \"base.h\"\n\nnamespace tsb {\n\n");
        printf("struct ReferenceHash {\n    const char* id;\n    u64 standard;\n    u64 quick;\n};\n\n");
        printf("static const ReferenceHash kReferenceHashes[] = {\n");
        for (int t = 0; t < 4; ++t)
            printf("    {\"%s\", 0x%016llxull, 0x%016llxull},\n", ids[t], (unsigned long long)h[t][MODE_STANDARD],
                   (unsigned long long)h[t][MODE_QUICK]);
        printf("};\n\n}  // namespace tsb\n");
    } else {
        for (int t = 0; t < 4; ++t)
            printf("%s standard=%016llx quick=%016llx\n", ids[t], (unsigned long long)h[t][MODE_STANDARD],
                   (unsigned long long)h[t][MODE_QUICK]);
    }
    return 0;
}
